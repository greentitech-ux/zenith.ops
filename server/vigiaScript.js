    '    Write-Host "Ele agora roda de: $Destino"',
    '    Write-Host "Pode APAGAR o arquivo que voce baixou - nao precisa mais dele."',
    '  } catch {',
    '    Escrever-Log "FALHA ao registrar a tarefa agendada: $($_.Exception.Message)"',
    '    Write-Host "ERRO ao instalar a tarefa agendada: $($_.Exception.Message)"',
    '    Write-Host "Rode o PowerShell como Administrador e tente de novo."',
    '  }',
    '  # ---- blindagem contra reinicio (precisa de Administrador). A tarefa de',
    '  # login acima so dispara quando ALGUEM loga - depois de um reinicio, a',
    '  # maquina ficava na tela de login e o NOCZenith nunca voltava (foi',
    '  # exatamente o que derrubou o parque em ago/2026: os reinicios da',
    '  # manutencao mataram os vigias um a um). A tarefa de BOOT roda como',
    '  # SYSTEM, sobe junto com o Windows sem depender de login, e cede a vez',
    '  # pra instancia de login quando ela existir (ver UiEstaAtiva).',
    '  $ehAdmin = $false',
    '  try { $ehAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator) } catch {}',
    '  if ($ehAdmin) {',
    '    try {',
    '      $acaoBoot = New-ScheduledTaskAction -Execute "powershell.exe" -Argument "-WindowStyle Hidden -ExecutionPolicy Bypass -File `"$Destino`" -Loop -Servico"',
    '      $gatilhoBoot = New-ScheduledTaskTrigger -AtStartup',
