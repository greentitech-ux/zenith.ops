// comando de UMA LINHA pra colar no PowerShell da loja (botao "Copiar comando"
// na tela NOC Zenith). Baixa o script DIRETO pra pasta fixa
// (%LOCALAPPDATA%\NOCZenith) via Invoke-RestMethod - arquivo baixado assim NAO
// recebe o "Mark of the Web", entao o Controle de Aplicativo Inteligente do
// Windows 11 NAO bloqueia (que e o que trava o clique-direito num .ps1 baixado
// pelo navegador). O X-NOC-Token autentica na rota mesmo em reinstalacao (quando
// o computador ja tem segredo). Depois roda o arquivo (& $f), que se instala
// como tarefa agendada apontando pra essa mesma pasta fixa.
function montarComandoInstalacao({ codigo, posto, tipo, agentToken, windowsAntigo, ehServidor }) {
  const token = String(agentToken || '').replace(/[^a-f0-9]/gi, '');
  // encodeURIComponent NAO escapa o apostrofo ('), e a URL entra dentro de uma
  // string PowerShell de ASPAS SIMPLES ('...') abaixo - entao um codigo com
  // apostrofo (ex: "Domino's Carrinho...") fecharia a string ali e quebraria/
  // injetaria o comando. Trocar ' por %27 (que o servidor decodifica de volta)
  // mantem a URL correta e blindada dentro das aspas simples.
  const enc = (s) => encodeURIComponent(s).replace(/'/g, '%27');
  const url = `${APP_BASE_URL}/api/loja-status/${enc(codigo)}/computadores/${enc(posto)}/vigia.ps1?tipo=${enc(tipo)}`;
  // o script real (baixa direto pra pasta fixa - sem Mark of the Web, entao o
  // Controle de Aplicativo Inteligente nao bloqueia - e roda de la)
  const script = [
    // GUARDA DE VERSAO, antes de tudo. No PowerShell 2.0 (Windows 7 e Server
    // 2008 R2) a primeira coisa que o instalador faz - Invoke-RestMethod -
    // nem existe, e a pessoa recebe "nao e reconhecido como nome de cmdlet"
    // no meio de 300 caracteres de comando: 20 minutos de mistério pra um
    // diagnóstico de 5 segundos (caso real da MAKELINE da Dom Bessa,
    // 13/09/2026).
    //
    // E o aviso diz a verdade inteira, incluindo a parte que decepciona:
    // instalar o PowerShell novo NAO resolve. Register-ScheduledTask,
    // Get-NetAdapter, Get-PhysicalDisk e Get-Volume sao modulos do Windows
    // 8/Server 2012 pra frente - nao vem com PowerShell nenhum no Windows 7.
    // Sem essa frase, a pessoa gasta a tarde instalando o WMF 5.1 pra
    // descobrir que o agente morre no primeiro reboot.
    //
    // Em PowerShell 2.0 o agente nao consegue rodar. Fecha imediatamente, sem
    // deixar uma janela de diagnostico exposta na tela da operacao.
    "if ($PSVersionTable.PSVersion.Major -lt 3) { exit }",
    "$ErrorActionPreference='Stop'",
    // Windows antigo: TLS 1.2 ANTES do download - a 19855 morria aqui, antes
    // de baixar qualquer coisa (ver adaptarParaWindowsAntigo). Padrao: nada.
    ...(windowsAntigo ? ['try{[Net.ServicePointManager]::SecurityProtocol=[Net.ServicePointManager]::SecurityProtocol -bor 3072}catch{}'] : []),
    "$d=Join-Path $env:LOCALAPPDATA 'NOCZenith'",
    'New-Item -ItemType Directory -Path $d -Force|Out-Null',
    "$f=Join-Path $d 'NOCZenith.ps1'",
    `Invoke-RestMethod -Uri '${url}' -Headers @{'X-NOC-Token'='${token}'} -OutFile $f`,
    'Unblock-File -Path $f -ErrorAction SilentlyContinue',
    '& $f',
  ].join(';');
  // -EncodedCommand (Base64 de UTF-16LE): o comando vira uma string opaca, sem
  // nenhum $ ou aspas soltos. Sem isso, colar `powershell -Command "...$f..."`
  // DENTRO de outro PowerShell fazia o shell de fora expandir $d/$f (que nao
  // existem la) e o comando chegava com -OutFile/-Path/& vazios (erro real da
  // loja). Assim cola e roda igual no PowerShell, no CMD ou no Executar.
  const b64 = Buffer.from(script, 'utf16le').toString('base64');
  const comandoDireto = `powershell -NoProfile -ExecutionPolicy Bypass -EncodedCommand ${b64}`;

  // Estacoes e PDVs precisam sempre da tarefa _Boot como SYSTEM: ela e' quem
  // mantem o monitoramento e os comandos administrativos depois de reiniciar.
  // Antes o botao apenas COPIAVA o instalador; se a pessoa abrisse o
  // PowerShell normal (o mais comum), o instalador seguia sem elevacao e
  // criava so a tarefa de login. Este invólucro abre a janela UAC do Windows e
  // so entao executa o instalador real elevado. Nao tenta contornar UAC: se a
  // confirmacao for cancelada, nao instala nem altera a maquina.
  //
  // Servidores e VMs marcados como servidor ficam exatamente como eram. Eles
  // nao recebem uma solicitacao UAC nova nem uma janela extra na operacao.
  if (ehServidor) return comandoDireto;

  const elevador = [
    "$ErrorActionPreference='Stop';",
    `try { $p = Start-Process -FilePath 'powershell.exe' -Verb RunAs -ArgumentList '-NoProfile -ExecutionPolicy Bypass -EncodedCommand ${b64}' -PassThru -Wait -ErrorAction Stop; exit [int]$p.ExitCode }`,
    "catch { [Console]::Error.WriteLine('Instalacao NOCZenith nao foi autorizada no UAC. Nenhuma alteracao foi feita.'); exit 1 }",
  // "try { } catch { }" e' uma unica instrucao no PowerShell: nao pode haver
  // ponto e virgula entre a chave e o catch, ou o parser acusa MissingCatch.
  ].join(' ');
  const b64Elevador = Buffer.from(elevador, 'utf16le').toString('base64');
  return `powershell -NoProfile -ExecutionPolicy Bypass -EncodedCommand ${b64Elevador}`;
}

