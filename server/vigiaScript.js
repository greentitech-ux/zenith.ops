    '    if ($script:UltimoBeatOkEm -ne $null -and (([DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds() - $script:UltimoBeatOkEm) -gt $LimiteTickMs)) { Bater-Rapido }',
